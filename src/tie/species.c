/*
 * Hyperspace starburst data uses the 0x40 line-object format consumed by
 * DRAWPOL_drawpolyobject's line path (drawpol.c): 4-byte header
 * (type, dedup, numpoints, numedges) then numpoints PolyVerts (6 B
 * each, signed i16 x/y/z) then numedges 5-byte edge records
 * {thickness_lo, thickness_hi, v1, v2, color}.
 *
 * Runtime mutations during anim_dohyperspace:
 *   +6  (point[0].y)  — near endpoint of the streak (animated)
 *   +12 (point[1].y)  — far endpoint of the streak (animated)
 *   +20 (edge.color)  — per-star shade, draw_drawhyperstar sets to
 *                       (star_idx & 3) - 4 each call.
 */
uint8_t hyperstardata[24] = {
	0x40, 0x00, 0x02, 0x01,             /* [0..3]   type=0x40, dedup, numpoints=2, numedges=1 */
	0x00, 0x00, 0x00, 0x00, 0x00, 0x00, /* [4..9]   point[0] = (0,0,0) — runtime writes .y at +6 */
	0x00, 0x00, 0x00, 0x0E, 0x00, 0x00, /* [10..15] point[1] = (0,0x0E00,0) — runtime writes .y at +12 */
	0x40, 0x00, 0x00, 0x01, 0xF8,       /* [16..20] edge: thickness=0x0040, v1=0, v2=1, color=0xF8 */
	0x00, 0x00, 0x00,                   /* [21..23] pad */
};

